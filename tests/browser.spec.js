import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createServer, BASE } from '../scripts/server.js';
import { existsSync } from 'node:fs';
test('interfaz, pagos, PWA offline y actualización real de caché', {timeout:120000}, async () => {
  let nextVersion = false;
  const server = createServer((file,data) => nextVersion && file === 'sw.js' ? data.toString().replace("'1.4.0'", "'1.4.0-test'") : data);
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const edge='C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
  const browser=await chromium.launch({headless:true,...(existsSync(edge)?{executablePath:edge}:{})});
  try {
    const context=await browser.newContext();
    let calls=0, fail=false;
    await context.route('https://api.frankfurter.dev/**',route=>{calls++;return fail?route.abort():route.fulfill({json:{date:new Date().toISOString().slice(0,10),base:'USD',quote:'MXN',rate:18}});});
    const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
    const url=`http://localhost:${server.address().port}${BASE}`;
    await page.goto(url);
    await page.waitForFunction(()=>document.querySelector('#rate-value').textContent.includes('$18'));
    await page.evaluate(()=>navigator.serviceWorker.ready);
    await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
    assert.equal(await page.locator('#pwa-update').isHidden(),true);
    await page.locator('#prices input').fill('350');
    await page.locator('input[value=USD]').check();
    await page.locator('#received-usd').fill('25');
    assert.equal(await page.locator('#change').textContent(),'$100.00 MXN');
    assert.equal(await page.locator('#usd-total').textContent(),'$19.45 USD');
    await page.locator('input[value=combined]').check();
    await page.getByRole('button',{name:'Agregar 200 MXN',exact:true}).click();
    await page.getByRole('button',{name:'Agregar 10 USD',exact:true}).click();
    assert.equal(await page.locator('#change').textContent(),'$30.00 MXN');
    await page.getByRole('button',{name:'Agregar 10 USD',exact:true}).click();
    assert.equal(await page.locator('#received-mxn').inputValue(),'200.00');
    assert.equal(await page.locator('#received-usd').inputValue(),'20.00');
    await page.locator('#prices input').fill('350.05');
    await page.locator('#received-mxn').fill('200.10');await page.locator('#received-usd').fill('8.33');
    assert.equal(await page.locator('#change').textContent(),'$0.01 MXN');
    assert.match(await page.locator('#change-label').textContent(),/Falta/);
    await page.locator('#rate-mode').selectOption('manual');await page.locator('#manual-rate').fill('0');
    assert.equal(await page.locator('#change').textContent(),'—');
    await page.locator('#manual-rate').fill('18');await page.locator('#reset').click();await page.locator('#physical-discard').check();await page.getByRole('button',{name:'Descartar cuenta',exact:true}).click();await page.locator('#cash-dialog').waitFor({state:'hidden'});
    assert.equal(await page.locator('#manual-rate').inputValue(),'18');
    assert.equal(await page.locator('#received-mxn').inputValue(),'');
    await page.locator('#prices input').fill('350');
    for(const width of [360,390,768,1280]){
      await page.setViewportSize({width,height:900});
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
      assert.ok(await page.locator('#mxn-bills button').first().evaluate(el=>el.getBoundingClientRect().height>=44));
      await page.screenshot({path:`test-results/view-${width}.png`,fullPage:true});
    }
    await page.locator('#rate-mode').selectOption('auto');fail=true;await page.locator('#refresh').click();
    await page.waitForFunction(()=>document.querySelector('#rate-status').textContent.includes('No se pudo'));
    assert.equal(await page.locator('#change').textContent(),'—');
    assert.equal(await page.locator('#saved-option').isEnabled(),true);
    await context.setOffline(true);
    await page.reload();
    await page.waitForFunction(()=>document.querySelector('#connection').textContent.includes('Sin conexión'));
    const offlineCalls=calls;
    assert.equal(await page.locator('#rate-value').textContent(),'Tasa no disponible');
    assert.ok(await page.locator('#refresh').isDisabled());
    await page.locator('input[value=combined]').check();await page.locator('#prices input').fill('350');
    await page.locator('#received-mxn').fill('200');await page.locator('#received-usd').fill('10');
    assert.equal(await page.locator('#change').textContent(),'—');
    await page.locator('#rate-mode').selectOption('saved');
    assert.equal(await page.locator('#change').textContent(),'$30.00 MXN');
    assert.match(await page.locator('#payment-rate').textContent(),/Referencia anterior/);
    await page.locator('input[value=MXN]').check();await page.locator('#received-mxn').fill('400');
    assert.equal(await page.locator('#change').textContent(),'$50.00 MXN');assert.equal(calls,offlineCalls);
    fail=false;await context.setOffline(false);
    await page.waitForFunction(()=>document.querySelector('#saved-info').textContent.includes('$18'));
    const manifest=await page.evaluate(async()=>await(await fetch('./manifest.webmanifest')).json());
    assert.equal(manifest.scope,'./');assert.equal(manifest.icons.length,2);
    await page.evaluate(()=>caches.open('unrelated-app').then(c=>c.put('/other',new Response('preservar'))));
    nextVersion=true;
    await page.evaluate(async()=>{const reg=await navigator.serviceWorker.getRegistration();await reg.update();});
    await page.locator('#pwa-update').waitFor({state:'visible'});
    assert.equal(await page.locator('#change').textContent(),'$50.00 MXN');
    await page.locator('#apply-update').click();
    await page.waitForFunction(async()=> (await caches.keys()).some(k=>k.endsWith('1.4.0-test')) && !(await caches.keys()).some(k=>k.endsWith(':1.4.0')));
    await page.waitForFunction(()=>document.querySelector('#prices input')?.value==='350');
    assert.ok((await page.evaluate(()=>caches.keys())).includes('unrelated-app'));
    const cacheURLs=await page.evaluate(async()=>{const keys=await caches.keys();const c=await caches.open(keys.find(k=>k.endsWith('1.4.0-test')));return(await c.keys()).map(r=>r.url);});
    assert.ok(cacheURLs.every(u=>u.startsWith(url)));
    assert.ok(!cacheURLs.some(u=>u.includes('frankfurter')));
    assert.deepEqual(errors,[]);
    console.log('OK: pagos, billetes, decimales, faltantes, persistencia, offline, rutas, actualización y aislamiento de caché.');
  } finally {await browser.close();await new Promise(resolve=>server.close(resolve));}
});
